#!/usr/bin/env python3
"""Regenerate docs/CHECKLIST.md from docs/COVERAGE.md plus a status sidecar.

Why a sidecar: COVERAGE.md is generated by `screens.py` and CHECKLIST.md is
derived from it, so neither is the right place to record progress — both get
overwritten. `tools/checklist_status.json` is the only hand-edited file, and it
holds story -> status. Regenerating is then always safe.

Usage:
    python tools/update_checklist.py                    # regenerate from sidecar
    python tools/update_checklist.py US-AD04 pass       # set one story, then regenerate
    python tools/update_checklist.py US-AD04            # show one story
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
COVERAGE = ROOT / "docs" / "COVERAGE.md"
SIDECAR = ROOT / "tools" / "checklist_status.json"
OUT = ROOT / "docs" / "CHECKLIST.md"

MILESTONES = ["M0", "M1", "M2", "M3", "M4"]
STATUSES = {"pass": "✅ PASS", "wip": "🔨 dikerjakan", "todo": "⬜", "defer": "⏸️ ditunda", "fail": "❌ gagal"}


def parse_coverage():
    text = COVERAGE.read_text(encoding="utf-8")
    rows = re.findall(r"^\| `(US-AD\d+)` \| (\w+) \| (M\d) \| (.+?) \| (.+?) \|$", text, re.M)
    if not rows:
        sys.exit("no stories parsed from COVERAGE.md — did its table format change?")
    return rows


def load_sidecar():
    if SIDECAR.exists():
        return json.loads(SIDECAR.read_text(encoding="utf-8"))
    return {}


def render(rows, status):
    by = {}
    for sid, pri, ms, title, scr in rows:
        by.setdefault(ms, []).append((sid, pri, title, scr))

    unknown = set(status) - {r[0] for r in rows}
    if unknown:
        sys.exit(f"sidecar names stories that are not in COVERAGE.md: {sorted(unknown)}")

    out = [
        "# CHECKLIST — AgentDeck M0 → M4",
        "",
        "> Dihasilkan oleh `tools/update_checklist.py` dari `docs/COVERAGE.md` + `tools/checklist_status.json`.",
        "> **Jangan edit file ini** — edit sidecar-nya, lalu jalankan ulang tool-nya.",
        "> Status: ✅ PASS · 🔨 dikerjakan · ⬜ belum · ⏸️ ditunda (keputusan user) · ❌ gagal",
        "",
        "| Story | Pri | MS | Judul | Layar | Status |",
        "|---|---|---|---|---|---|",
    ]
    for ms in MILESTONES:
        for sid, pri, title, scr in sorted(by[ms]):
            out.append(f"| `{sid}` | {pri} | {ms} | {title} | {scr} | {STATUSES[status.get(sid, 'todo')]} |")

    total = sum(len(by[m]) for m in MILESTONES)
    passed = sum(1 for m in MILESTONES for r in by[m] if status.get(r[0]) == "pass")
    deferred = sum(1 for m in MILESTONES for r in by[m] if status.get(r[0]) == "defer")
    out += ["", f"**Total M0–M4: {total} story** ({passed} PASS, {deferred} ditunda)", ""]
    out += ["## Progres per milestone", "", "| Milestone | Story | PASS | Sisa |", "|---|---|---|---|"]
    for ms in MILESTONES:
        n = len(by[ms])
        p = sum(1 for r in by[ms] if status.get(r[0]) == "pass")
        out.append(f"| {ms} | {n} | {p} | {n - p} |")
    out.append("")
    out += render_notes(status)
    return "\n".join(out)


