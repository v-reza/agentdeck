def render_notes(status):
    """Per-story caveats, emitted only for stories currently in the noted state."""
    blocks = []
    for sid, (want, headline, bullets) in NOTES.items():
        if status.get(sid) != want:
            continue
        blocks += [f"### Catatan status — `{sid}` ({STATUSES[want]})", "", f"**{headline}.**", ""]
        blocks += [f"- {b}" for b in bullets]
        blocks.append("")
    return blocks


def main(argv):
    rows = parse_coverage()
    status = load_sidecar()

    if len(argv) >= 2:
        sid = argv[1]
        if len(argv) == 2:
            print(f"{sid}: {status.get(sid, 'todo')}")
            return 0
        word = argv[2].lower()
        if word not in STATUSES:
            sys.exit(f"unknown status {word!r}; pick one of {sorted(STATUSES)}")
        if sid not in {r[0] for r in rows}:
            sys.exit(f"{sid} is not a story in COVERAGE.md")
        status[sid] = word
        SIDECAR.parent.mkdir(parents=True, exist_ok=True)
        SIDECAR.write_text(json.dumps(status, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        print(f"{sid} -> {word}")

    OUT.write_text(render(rows, status) + "\n", encoding="utf-8")
    passed = sum(1 for v in status.values() if v == "pass")
    print(f"wrote {OUT.relative_to(ROOT)} ({passed} PASS, {len(status)} tracked)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
